def translate_text(text, lang='English', **kwargs):
    """
    Translates a phrase or key into the requested language.
    If the requested language is 'English' or the phrase is not found,
    the original text (formatted with kwargs if provided) is returned.
    """
    if not text:
        return text

    if not lang or lang == 'English':
        result = text
    else:
        lang_dict = TRANSLATIONS.get(lang, {})
        result = lang_dict.get(text, text)

    if kwargs:
        try:
            return result.format(**kwargs)
        except Exception:
            return result

    return result

